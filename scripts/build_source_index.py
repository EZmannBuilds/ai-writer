#!/usr/bin/env python3
"""Build research/source-index.md from the entries in research/core/ and research/packs/.

    python3 scripts/build_source_index.py          # rewrite the index
    python3 scripts/build_source_index.py --check  # exit 1 if the index is stale

Entries are the single source of truth; never edit the index by hand.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INDEX = os.path.join(ROOT, "research", "source-index.md")

HEADER = """# Source Index

Every research source AI Writer uses, one row per citation key. Generated by `scripts/build_source_index.py` from the entries in `research/core/` and `research/packs/` — edit the entries, then rebuild.

Cite a source inline as `[@key]`. `scripts/validate.py` fails on any key that isn't listed here.

**Fidelity** says how closely AI Writer implements what the source describes: `exact`, `approximate` (the source uses tools a text-only skill lacks), `conceptual` (an idea, not a method), `convention` (a craft or genre convention, not evidence), or `design` (no external source).

| Key | Source | Type | Fidelity | Entry |
|---|---|---|---|---|
"""


def short(source, limit=90):
    s = re.sub(r"\s*https?://\S+", "", source).strip().rstrip(".;")
    return s if len(s) <= limit else s[: limit - 1].rstrip() + "…"


def entries():
    rows = []
    for sub in ("core", "packs"):
        d = os.path.join(ROOT, "research", sub)
        for f in sorted(os.listdir(d)):
            if not f.endswith(".md"):
                continue
            text = open(os.path.join(d, f), encoding="utf-8").read()
            parts = re.split(r"^### `([\w-]+)`\s*$", text, flags=re.M)
            for i in range(1, len(parts), 2):
                key, body = parts[i], parts[i + 1]
                field = lambda name: (re.search(r"^- \*\*%s:\*\*\s*(.+)$" % name, body, re.M) or [None, ""])[1]
                fidelity = field("Fidelity").split(" ")[0].strip("—").strip()
                rows.append((key, short(field("Source")).replace("|", "\\|"), field("Type"),
                             fidelity, "[%s/%s](%s/%s#%s)" % (sub, f, sub, f, key)))
    return sorted(rows)


def render():
    return HEADER + "".join("| `%s` | %s | %s | %s | %s |\n" % r for r in entries())


def main():
    new = render()
    if "--check" in sys.argv:
        old = open(INDEX, encoding="utf-8").read() if os.path.exists(INDEX) else ""
        if old != new:
            print("research/source-index.md is stale; run scripts/build_source_index.py")
            return 1
        return 0
    with open(INDEX, "w", encoding="utf-8") as fh:
        fh.write(new)
    print("wrote %d sources" % len(entries()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
